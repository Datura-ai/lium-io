"""The attest-agent: what it proves, what it refuses, and what it cannot reach.

The TDX quote and the NVIDIA evidence are the two things a test process cannot produce —
there is no TDX here and no CC-capable GPU — so those two calls are the seam. Everything
around them is real: a real EC key generated by the real code, the real `report_data`
construction, the real routes.

That split is deliberate rather than convenient. The quote is opaque bytes from hardware;
what this suite can actually check is whether the agent asks for a quote over the *right*
64 bytes, and whether it ever produces two different ones for a single challenge. Both are
properties of this code, and both are where a bug would be silent on hardware.
"""

